  async listOverview(
    ctx: RequestUserContext,
    query: {
      from?: string;
      to?: string;
      page?: number;
      pageSize?: number;
    },
  ): Promise<{ items: AttendanceOverviewItem[]; total: number; page: number; pageSize: number }> {
    this.authz.requirePermission(ctx, MONITOR_READ);
    const scope = this.authz.accessibleDistrictIds(ctx);
    const pageNum = query.page ?? 1;
    const pageSize = query.pageSize ?? 20;
    const page = await this.repo.listOverview({
      jurisdictionIds: scope ? [...scope] : undefined,
      from: query.from,
      to: query.to,
      page: pageNum,
      pageSize,
    });
    const openCounts = await this.repo.countOpenAnomaliesByProject({
      jurisdictionIds: scope ? [...scope] : undefined,
    });
    const countByProject = new Map(openCounts.map((r) => [r.projectId, r.count]));

    const items: AttendanceOverviewItem[] = page.items.map((c) => ({
      projectId: c.projectId,
      projectCode: c.projectCode,
      projectName: c.projectName,
      districtId: c.districtId,
      windowId: c.windowId,
      windowCode: "",
      operationalDate: c.operationalDate,
      expected: c.expected,
      present: c.present,
      coverage: c.coverage,
      dataQuality: c.dataQuality,
      openAnomalyCount: countByProject.get(c.projectId) ?? 0,
      latestComputedAt: c.computedAt,
      sourceCounts: c.sourceCounts,
    }));
    return { items, total: page.total, page: pageNum, pageSize };
  }

