/* ---------- Helpers ---------- */

function localWindowBounds(opDate: string, startTime: string, endTime: string): { start: Date; end: Date } {
  const [sh, sm] = startTime.split(":").map(Number);
  const [eh, em] = endTime.split(":").map(Number);
  const start = new Date(`${opDate}T${startTime}:00.000Z`);
  let end = new Date(`${opDate}T${endTime}:00.000Z`);
  if (end.getTime() <= start.getTime()) {
    end = new Date(end.getTime() + 24 * 3_600_000);
  }
  void sh;
  void sm;
  void eh;
  void em;
  return { start, end };
}

function daysBefore(opDate: string, days: number): string {
  const d = new Date(`${opDate}T00:00:00.000Z`);
  d.setUTCDate(d.getUTCDate() - days);
  return d.toISOString().slice(0, 10);
}

export function buildAttendanceCsv(rows: AttendanceCalculation[]): string {
  const header = [
    "operationalDate",
    "projectId",
    "windowId",
    "expected",
    "present",
    "absent",
    "unknown",
    "sourceBiometric",
    "sourceReported",
    "sourceCctv",
    "coverage",
    "dataQuality",
    "computedAt",
  ];
  const lines = rows.map((r) =>
    [
      r.operationalDate,
      r.projectId,
      r.windowId,
      r.expected ?? "",
      r.present,
      r.absent ?? "",
      r.unknown,
      r.sourceCounts.BIOMETRIC ?? "",
      r.sourceCounts.INSTITUTION_REPORTED ?? "",
      r.sourceCounts.CCTV ?? "",
      r.coverage,
      r.dataQuality,
      r.computedAt,
    ]
      .map((v) => String(v).replace(/"/g, '""'))
      .map((v) => `"${v}"`)
      .join(","),
  );
  return [header.join(","), ...lines].join("\n");
}