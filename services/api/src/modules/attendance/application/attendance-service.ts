  async downloadExport(ctx: RequestUserContext, id: string): Promise<{ csv: Buffer; filename: string }> {
    this.authz.requirePermission(ctx, EXPORT);
    const record = await this.repo.findExportById(id);
    if (!record) throw AppError.notFound("Attendance export not found.");
    await this.requireProjectScope(ctx, record.projectId, EXPORT);

    if (record.status === "EXPIRED") {
      throw AppError.badRequest("Export artifact has expired (retention window elapsed).");
    }
    if (record.status !== "READY" || !record.artifactKey) {
      throw AppError.conflict(`Export is not ready (status=${record.status}).`);
    }
    const stream = await this.deps.storage.get(record.artifactKey);
    const chunks: Buffer[] = [];
    for await (const chunk of stream) chunks.push(chunk as Buffer);
    const csv = Buffer.concat(chunks);

    await this.repo.updateExport(id, { downloadedAt: new Date() });
    await this.repo.recordAudit({
      actorUserId: ctx.userId,
      requestId: ctx.requestId ?? null,
      ipAddress: ctx.ipAddress ?? null,
      auditAction: "attendance.export_downloaded",
      auditMetadata: { exportId: id, recordCount: record.recordCount },
      resourceType: "attendance-export",
      resourceId: id,
    });
    return { csv, filename: `netram-attendance-${id.slice(0, 8)}.csv` };
  }

  /** Idempotent export cleanup: expires READY exports past retention (§40). */
