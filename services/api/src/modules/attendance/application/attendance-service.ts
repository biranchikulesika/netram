  async decideCorrection(
    ctx: RequestUserContext,
    correctionId: string,
    decision: "approve" | "reject",
  ): Promise<AttendanceCorrection> {
    this.authz.requirePermission(ctx, CORRECTION_APPROVE);
    const correction = await this.repo.findCorrectionById(correctionId);
    if (!correction) throw AppError.notFound("Attendance correction not found.");
    await this.requireProjectScope(ctx, correction.projectId, CORRECTION_APPROVE);

    if (correction.status !== "PENDING") {
      throw AppError.conflict(`Correction is already ${correction.status.toLowerCase()}.`);
    }
    // Independent approval: the requester cannot approve their own correction (§34).
    if (correction.requestedBy === ctx.userId) {
      throw AppError.forbidden("Approval must be made by a different authority than the requester.");
    }

    if (decision === "reject") {
      const rejected = await this.repo.updateCorrectionStatus(correctionId, "REJECTED", ctx.userId);
      await this.repo.recordAudit({
        actorUserId: ctx.userId,
        requestId: ctx.requestId ?? null,
        ipAddress: ctx.ipAddress ?? null,
        auditAction: "attendance.correction_rejected",
        auditMetadata: { correctionId, projectId: correction.projectId },
        resourceType: "attendance-correction",
        resourceId: correctionId,
      });
      return rejected!;
    }

    // Approve: apply the change to the target (calculation present today).
    if (correction.targetType === "calculation" && correction.field === "present") {
      const present = Number(correction.newValue.present);
      if (!Number.isInteger(present) || present < 0) {
        throw AppError.badRequest("newValue.present must be a non-negative integer.");
      }
      const calc = await this.repo.findCalculationById(correction.targetId);
      if (!calc) throw AppError.notFound("Attendance calculation not found.");
      const expected = calc.expected;
      const absent =
        expected !== null && calc.coverage === "COMPLETE" ? Math.max(0, expected - present) : null;
      const unknown =
        expected !== null ? Math.max(0, expected - present) : 0;
      await this.repo.updateCalculationDerived(correction.targetId, { present, absent, unknown });
    } else if (correction.targetType === "calculation") {
      throw AppError.badRequest("Only the calculation 'present' field is supported for correction.");
    } else {
      throw AppError.badRequest("Only calculation corrections are supported in this version.");
    }

    const approved = await this.repo.updateCorrectionStatus(correctionId, "APPROVED", ctx.userId);
    await this.repo.recordAudit({
      actorUserId: ctx.userId,
      requestId: ctx.requestId ?? null,
      ipAddress: ctx.ipAddress ?? null,
      auditAction: "attendance.correction_approved",
      auditMetadata: { correctionId, projectId: correction.projectId, targetId: correction.targetId, field: correction.field },
      resourceType: "attendance-correction",
      resourceId: correctionId,
    });
    await this.repo.enqueueEvent({
      type: "attendance.correction_approved",
      correlationId: correctionId,
      actorUserId: ctx.userId,
      resourceType: "attendance-correction",
      resourceId: correctionId,
      payload: { correctionId, projectId: correction.projectId },
    });
    return approved!;
  }

