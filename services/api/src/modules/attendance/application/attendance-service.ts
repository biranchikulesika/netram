  async reviewAnomaly(
    ctx: RequestUserContext,
    anomalyId: string,
    input: {
      action: "acknowledge" | "dismiss" | "false_positive" | "investigate" | "actioned" | "link_inspection" | "link_complaint" | "note";
      note?: string | null;
      linkedInspectionId?: string | null;
      linkedComplaintId?: string | null;
    },
  ): Promise<AttendanceAnomaly> {
    const anomaly = await this.repo.findById(anomalyId);
    if (!anomaly) throw AppError.notFound("Attendance anomaly not found.");
    this.authz.requirePermission(ctx, ANOMALY_REVIEW, { districtId: anomaly.districtId });

    const stateForAction: Partial<Record<typeof input.action, AttendanceAnomalyState>> = {
      acknowledge: "REVIEWED",
      dismiss: "DISMISSED",
      false_positive: "FALSE_POSITIVE",
      investigate: "INVESTIGATING",
      actioned: "ACTIONED",
    };

    const note = input.note ?? null;
    const reviewAction = input.action;
    const auditAction: AuditAction =
      input.action === "dismiss"
        ? "attendance.anomaly_dismissed"
        : input.action === "false_positive"
          ? "attendance.anomaly_false_positive"
          : input.action === "investigate"
            ? "attendance.anomaly_investigating"
            : input.action === "actioned"
              ? "attendance.anomaly_actioned"
              : "attendance.anomaly_reviewed";
    const eventType: DomainEventType =
      input.action === "dismiss"
        ? "attendance.anomaly_dismissed"
        : input.action === "false_positive"
          ? "attendance.anomaly_false_positive"
          : input.action === "investigate"
            ? "attendance.anomaly_investigating"
            : input.action === "actioned"
              ? "attendance.anomaly_actioned"
              : "attendance.anomaly_reviewed";

    const to = stateForAction[input.action] ?? anomaly.state;
    if (to !== anomaly.state) {
      evaluateAttendanceAnomalyTransition(anomaly.state, to);
    }

    const updated = await this.repo.transitionAnomaly({
      anomalyId,
      to,
      reviewedBy: ctx.userId,
      reviewedAt: new Date(),
      reviewNotes: note,
      linkedInspectionId: input.linkedInspectionId,
      linkedComplaintId: input.linkedComplaintId,
      groupId: anomaly.groupId,
      reviewAction: reviewAction as never,
      audit: {
        actorUserId: ctx.userId,
        requestId: ctx.requestId ?? null,
        ipAddress: ctx.ipAddress ?? null,
        auditAction,
        auditMetadata: {
          from: anomaly.state,
          to,
          action: input.action,
          note,
          anomalyType: anomaly.anomalyType,
        },
        resourceType: "attendance-anomaly",
        resourceId: anomalyId,
      },
      event: {
        type: eventType,
        correlationId: anomalyId,
        actorUserId: ctx.userId,
        resourceType: "attendance-anomaly",
        resourceId: anomalyId,
        payload: {
          anomalyId,
          from: anomaly.state,
          to,
          action: input.action,
          anomalyType: anomaly.anomalyType,
          severity: anomaly.severity,
        },
      },
    });

    // Close the persistent group when the anomaly reaches a terminal state.
    if (anomaly.groupId && ["DISMISSED", "FALSE_POSITIVE", "ACTIONED"].includes(to)) {
      await this.repo.updateGroupState(anomaly.groupId, to, new Date());
    }
    return updated;
  }

  /* ---------- Individual drill-down (§37) ---------- */

  async drillDown(
    ctx: RequestUserContext,
    query: {
      projectId: string;
      personExternalId: string;
      windowId?: string;
      operationalDate?: string;
      from?: string;
      to?: string;
    },
  ): Promise<AttendanceDrillDownRow[]> {
    this.authz.requirePermission(ctx, INDIVIDUAL_READ);
    await this.requireProjectScope(ctx, query.projectId, INDIVIDUAL_READ);

    const rows = await this.repo.listEventsForPerson(query.projectId, query.personExternalId, {
      windowId: query.windowId,
      operationalDate: query.operationalDate,
      from: query.from,
      to: query.to,
    });

    // Every authorized individual-level access is audited and emitted as a durable event (§37, §46).
    const accessId = randomUUID();
    await this.repo.recordAudit({
      actorUserId: ctx.userId,
      requestId: ctx.requestId ?? null,
      ipAddress: ctx.ipAddress ?? null,
      auditAction: "attendance.individual_accessed",
      auditMetadata: {
        projectId: query.projectId,
        windowId: query.windowId ?? null,
        operationalDate: query.operationalDate ?? null,
        personExternalId: query.personExternalId,
        eventCount: rows.length,
      },
      resourceType: "attendance_person",
      resourceId: query.personExternalId,
    });
    await this.repo.enqueueEvent({
      type: "attendance.individual_accessed",
      correlationId: accessId,
      actorUserId: ctx.userId,
      resourceType: "attendance_person",
      resourceId: query.personExternalId,
      payload: {
        projectId: query.projectId,
        personExternalId: query.personExternalId,
        windowId: query.windowId ?? null,
        operationalDate: query.operationalDate ?? null,
        eventCount: rows.length,
      },
    });

    return rows.map((r) => ({
      personExternalId: r.personExternalId,
      netramUserId: r.netramUserId,
      eventType: r.eventType as AttendanceDrillDownRow["eventType"],
      occurredAt: r.occurredAt.toISOString(),
      deviceName: r.deviceName,
      windowCode: r.windowCode,
    }));
  }

  /* ---------- Ingestion (§6, §9, §19) ---------- */

  async syncDevice(
    ctx: RequestUserContext,
    deviceId: string,
    opts: { cursor?: string | null; operationalDate?: string },
  ): Promise<SyncDeviceResult & { deviceId: string; provider: string }> {
    this.authz.requirePermission(ctx, INGEST);
    const device = await this.repo.findDeviceById(deviceId);
    if (!device) throw AppError.notFound("Attendance device not found.");
    await this.requireProjectScope(ctx, device.projectId, INGEST);

    const cursor = opts.cursor ?? device.syncCursor;
    const events = opts.operationalDate
      ? await this.generateForDate(deviceId, opts.operationalDate, opts.cursor)
      : await this.deps.provider.sync(device, cursor);

    const result = await this.processDeviceEvents(device, events, ctx);

    const latestEventAt = events.reduce(
      (max, e) => (e.occurredAt.getTime() > max.getTime() ? e.occurredAt : max),
      new Date(0),
    );
    await this.repo.updateDeviceHealth(device.id, {
      status: "ONLINE",
      lastSeenAt: new Date(),
      lastEventAt: latestEventAt.getTime() > 0 ? latestEventAt : undefined,
      syncCursor: opts.cursor ?? device.syncCursor,
    });

    for (const key of result.affectedWindows) {
      await this.calculateWindow(ctx, key.windowId, key.operationalDate);
    }
    return { ...result, deviceId: device.id, provider: this.deps.provider.name };
  }

